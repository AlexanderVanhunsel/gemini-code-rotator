#!/usr/bin/env bash
# Generates litellm_config.yaml from the keys in .env.
# One model entry is created per GEMINI_API_KEY_<n> found, all under the same
# model name ("gemini-main"), so LiteLLM load-balances and retries across them.
set -euo pipefail

DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
cd "$DIR"

if [ ! -f .env ]; then
  echo "No .env found. Run ./install.sh first." >&2
  exit 1
fi

set -a
# shellcheck disable=SC1091
. ./.env
set +a

MODEL="${GEMINI_MODEL:-gemini/gemini-3.8-flash}"

# Collect the numbers of all GEMINI_API_KEY_<n> variables that have a value.
nums=()
while IFS='=' read -r name value; do
  case "$name" in
    GEMINI_API_KEY_[0-9]*)
      if [ -n "$value" ]; then nums+=("${name#GEMINI_API_KEY_}"); fi
      ;;
  esac
done < <(grep -E '^GEMINI_API_KEY_[0-9]+=' .env || true)

if [ "${#nums[@]}" -eq 0 ]; then
  echo "No GEMINI_API_KEY_<n> values found in .env." >&2
  exit 1
fi

{
  echo "# GENERATED by generate-config.sh - do not edit by hand."
  echo "# Change keys/model in .env and restart ./start.sh instead."
  echo "model_list:"
  for n in "${nums[@]}"; do
    echo "  - model_name: gemini-main"
    echo "    litellm_params:"
    echo "      model: ${MODEL}"
    echo "      api_key: os.environ/GEMINI_API_KEY_${n}"
  done
  cat <<'YAML'

router_settings:
  routing_strategy: simple-shuffle   # spread load across the keys
  num_retries: 5                     # on a 429, retry (on another key)
  allowed_fails: 1                   # one failure puts a key into cooldown
  cooldown_time: 60                  # seconds a rate-limited key rests

litellm_settings:
  drop_params: true                  # drop params Gemini does not support
  request_timeout: 600

general_settings:
  master_key: os.environ/LITELLM_MASTER_KEY
YAML
} > litellm_config.yaml.tmp

mv litellm_config.yaml.tmp litellm_config.yaml
echo "Generated litellm_config.yaml: ${#nums[@]} key(s), model ${MODEL}"
